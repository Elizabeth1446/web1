PRODUTO = input("Digite o nome do produto: ")
PREÇO = float(input("Digite o preço do produto: "))
QUANTIDADE = int(input("Digite a quantidade do produto: "))
PERCENTUAL_DESCONTO = float(input("Digite o percentual de desconto: "))
PARCELAS = int(input("Digite a quantidade de parcelas: "))

VALOR_BRUTO = int(PREÇO * QUANTIDADE)
VALOR_DESCONTO = int(VALOR_BRUTO * (PERCENTUAL_DESCONTO / 100))
VALOR_FINAL = int(VALOR_BRUTO - VALOR_DESCONTO)
VALOR_PARCELA = int(VALOR_FINAL / PARCELAS)
print("O valor total do produto é: R$ %.2f" % VALOR_BRUTO)
print("O valor do desconto é: R$ %.2f" % VALOR_DESCONTO)
print("O valor final do produto é: R$ %.2f" % VALOR_FINAL)
print("O valor de cada parcela é: R$ %.2f" % VALOR_PARCELA)
